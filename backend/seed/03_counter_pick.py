import sys
import os

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from database import get_db_connection

def seed_counter_pick():
    conn = get_db_connection()
    cur = conn.cursor()

    cur.execute("SELECT id_hero, name_hero FROM hero;")
    heroes = {row[1]: row[0] for row in cur.fetchall()}

    counters_reinhardt = [
        ('Раматтра', 'лучший', 
         'В форме Немезиды Раматтра игнорирует щит Райнхардта. Ультимейт Раматтры («Аннигиляция») тоже оставляет Райнхардта беззащитным.'),
        
        ('Ориса', 'лучший', 
         'Энергетическое копьё сбивает рывок Райнхардта, толкает его, не давая приблизиться к вашим союзникам. Защитное поле делает её неуязвимой для пинка и оглушения.'),
        
        ('Бастион', 'лучший', 
         'В режиме «Артиллерия» (или после смены режима на штурмовой) Бастион уничтожает щит Райнхардта за 3 секунды. Без щита Райнхардт становится мишенью, которую легко уничтожить.'),
        
        ('Сомбра', 'лучший', 
         'Взлом отключает щит Райнхардта. Без него он становится беззащитным посреди боя, из-за чего быстро умирает под фокусом команды Сомбры. Импульс (ультимейт) мгновенно убирает его барьер.'),
        
        ('Фарра', 'хороший', 
         'Благодаря способности полёта Фарра может атаковать Райнхардта сверху. При таком раскладе Райнхардт будет вынужден выбирать, от кого ему защищаться (от угрозы сверху или от остальной команды Фарры снизу).'),
        
        ('Эхо', 'хороший', 
         'Благодаря способности полёта Эхо может атаковать Райнхардта сверху. При таком раскладе Райнхардт будет вынужден выбирать, от кого ему защищаться (от угрозы сверху или от остальной команды Эхо снизу).'),
        
        ('Ана', 'хороший', 
         'Усыпление (выстрел из транквилизатора) — отличный способ остановить ультимейт или рывок Райнхардта.'),
        
        ('Мауга', 'хороший', 
         'Хоть Мауга медленно уничтожает щит, в дуэли с Райнхардом он одерживает победу с помощью способностей (разгон сердцебиения).'),
        
        ('D.Va', 'не брать', 
         'Ракеты D.Va поглощаются щитом Райнхардта, пушки очень медленно сносят щит. В итоге Райнхард подходит всё ближе и уничтожает D.Va. Матрикс D.Va не спасает от молота.'),
        
        ('Трейсер', 'не брать', 
         'Трейсер хоть и может бегать в спину Райнхардта, её урона будет крайне мало для его убийства. Она не сможет отвлекать на себя Райнхардта, так как ему необходимо держать щит и защищать союзников.')
    ]

    hero_name = 'Райнхардт'
    hero_id = heroes[hero_name]

    # Вставляем контрпики
    for counter_name, strength, description in counters_reinhardt:
        if counter_name in heroes:
            cur.execute("""
                INSERT INTO counter_pick (id_hero, id_enemy, strength, description_c)
                VALUES (%s, %s, %s, %s)
                ON CONFLICT (id_hero, id_enemy) DO UPDATE 
                SET strength = EXCLUDED.strength,
                    description_c = EXCLUDED.description_c;
            """, (hero_id, heroes[counter_name], strength, description))

    conn.commit()
    cur.close()
    conn.close()

if __name__ == "__main__":
    seed_counter_pick()